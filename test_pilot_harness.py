# --- CLI discovery ---------------------------------------------------------

def test_env_cli_takes_priority(monkeypatch, tmp_path):
    fake_cli = tmp_path / "opencode.exe"
    fake_cli.write_text("fake", encoding="utf-8")
    monkeypatch.setenv("OPENCODE_CLI", str(fake_cli))
    monkeypatch.setattr("pilot_opencode.shutil.which", lambda name: None)
    assert find_opencode_cli() == str(fake_cli.resolve())


def test_find_cli_candidates_includes_env(monkeypatch):
    monkeypatch.setenv("OPENCODE_CLI", "C:\\somewhere\\opencode.exe")
    candidates = find_cli_candidates()
    assert candidates[0] == "C:\\somewhere\\opencode.exe"


def test_find_cli_returns_none_without_install(monkeypatch):
    monkeypatch.delenv("OPENCODE_CLI", raising=False)
    monkeypatch.setattr("pilot_opencode.shutil.which", lambda name: None)
    monkeypatch.setattr("pilot_opencode.Path.is_file", lambda self: False)
    assert find_opencode_cli() is None


# --- Delivery sandbox ------------------------------------------------------

def test_delivery_sandbox_installs_plugin_and_copies_fixture(tmp_path):
    sandbox = build_delivery_sandbox(tmp_path, "treated", with_plugin=True)
    plugin = sandbox / ".opencode" / "plugins" / "cognigraph" / "index.ts"
    assert plugin.is_file()
    assert plugin.read_text(encoding="utf-8").startswith(
        "// Generated by CogniGraph.")
    manifest = json.loads(
        (sandbox / ".opencode" / "package.json").read_text(encoding="utf-8"))
    assert "@opencode/plugin" in manifest["dependencies"]
    db = sandbox / ".cognigraph" / "memory.db"
    assert db.is_file() and db.stat().st_size > 0
    # The sandbox DB must be the fixture copy, never the live repo DB.
    live_db = REPO_ROOT / ".cognigraph" / "memory.db"
    assert db.resolve() != live_db.resolve()
    assert (sandbox / "app.py").is_file()


def test_delivery_sandbox_control_has_no_plugin(tmp_path):
    sandbox = build_delivery_sandbox(tmp_path, "control", with_plugin=False)
    assert not (sandbox / ".opencode" / "plugins" / "cognigraph").exists()
    assert (sandbox / ".cognigraph" / "memory.db").is_file()


# --- Run event parsing / verdict -------------------------------------------

def test_extract_retrieval_id_variants():
    assert extract_retrieval_id("118") == 118
    assert extract_retrieval_id("NO_CONTEXT") == "NO_CONTEXT"
    assert extract_retrieval_id("I found 42 facts") is None
    assert extract_retrieval_id("") is None


def test_parse_run_events_sums_tokens_and_text():
    stdout = "\n".join([
        json.dumps({"type": "step_start", "sessionID": "ses_x",
                    "part": {"type": "step-start"}}),
        json.dumps({"type": "text", "sessionID": "ses_x",
                    "part": {"type": "text", "text": "hello"}}),
        json.dumps({"type": "step_finish", "sessionID": "ses_x",
                    "part": {"type": "step-finish", "cost": 0.0,
                             "tokens": {"input": 100, "output": 20}}}),
        json.dumps({"type": "step_finish", "sessionID": "ses_x",
                    "part": {"type": "step-finish", "cost": 0.0,
                             "tokens": {"input": 50, "output": 5}}}),
        "not json at all",
    ])
    summary = parse_run_events(stdout)
    assert summary["session_id"] == "ses_x"
    assert summary["tokens_in"] == 150
    assert summary["tokens_out"] == 25
    assert summary["assistant_text"] == "hello"


def test_verdict_confirmed():
    verdict, _ = verdict_from_arms(
        {"retrieval_id": 118, "answer": "118"},
        {"retrieval_id": "NO_CONTEXT", "answer": "NO_CONTEXT"})
    assert verdict == "delivery_confirmed"


def test_verdict_inconclusive_cases():
    verdict, reason = verdict_from_arms(
        {"retrieval_id": "NO_CONTEXT", "answer": "NO_CONTEXT"},
        {"retrieval_id": "NO_CONTEXT", "answer": "NO_CONTEXT"})
    assert verdict == "inconclusive" and "treated" in reason
    verdict, reason = verdict_from_arms(
        {"retrieval_id": 5, "answer": "5"},
        {"retrieval_id": 9, "answer": "9"})
    assert verdict == "inconclusive" and "control" in reason


# --- Task definitions --------------------------------------------------------

def test_tasks_are_wellformed_and_unique():
    ids = [t["id"] for t in TASKS]
    assert len(ids) == len(set(ids))
    for task in TASKS:
        assert task["prompt"].strip()
        assert task["seed_facts"], "task needs at least one seed fact"
        for fact in task["seed_facts"]:
            assert fact["category"] and fact["content"].strip()
        assert task["starter_files"]
        assert task["check_files"]
        assert task["check_cmd"]
        # The prompt must not state the convention it tests (no answer leak).
        seed_words = task["seed_facts"][0]["content"].lower()
        assert "from __future__" not in task["prompt"].lower() or \
            "future" not in seed_words


# --- Comparison sandbox + real bridge delivery ------------------------------

@pytest.mark.parametrize("task", TASKS, ids=lambda t: t["id"])
def test_task_sandbox_bridge_delivers_seed_fact(tmp_path, task):
    sandbox = build_task_sandbox(tmp_path, task, "treated")
    result = bridge_check(sandbox, task["prompt"])
    assert result["status"] == "ok", result
    seed_head = task["seed_facts"][0]["content"][:40]
    assert seed_head in result["markdown"]


def test_compare_dry_run_needs_no_cli(tmp_path):
    report = run_compare(None, tmp_path, TASKS[:1], "test-model", 60,
                         dry_run=True)
    assert report["dry_run"] is True
    outcomes = {(r["arm"], r["outcome"]) for r in report["results"]}
    assert ("treated", "dry_run") in outcomes
    assert ("control", "dry_run") in outcomes
    assert report["passed_summary"][TASKS[0]["id"]] == {
        "treated": 0, "control": 0}


def test_control_task_sandbox_has_no_readable_database(tmp_path):
    """Regression: in the first live run the control agents bypassed the
    missing plugin by reading the seeded DB directly with SQLite."""
    task = TASKS[0]
    sandbox = build_task_sandbox(tmp_path, task, "control")
    assert not (sandbox / ".cognigraph" / "memory.db").exists()
    treated = build_task_sandbox(tmp_path, task, "treated")
    assert (treated / ".cognigraph" / "memory.db").is_file()


def test_list_agent_files_detects_only_real_changes(tmp_path):
    task = TASKS[0]
    sandbox = build_task_sandbox(tmp_path, task, "control")
    assert list_agent_files(sandbox, task) == {
        "created": [], "modified": []}
    (sandbox / "new.py").write_text("x = 1\n", encoding="utf-8")
    (sandbox / "README.md").write_text("changed\n", encoding="utf-8")
    files = list_agent_files(sandbox, task)
    assert files["created"] == ["new.py"]
    assert files["modified"] == ["README.md"]
