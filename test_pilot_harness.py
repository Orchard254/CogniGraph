"""Tests for the live OpenCode pilot / comparison harnesses.

These tests cover harness internals WITHOUT a real OpenCode CLI or model
call, except for the bridge-delivery test which uses the real in-process
bridge (opencode_context.get_plugin_context) against an isolated temp DB.
Live runs are exercised manually via scripts/pilot_opencode.py and
scripts/pilot_compare.py; see docs/PILOT_OPENCODE.md.
"""
