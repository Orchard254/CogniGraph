"""Install CogniGraph's native OpenCode V2 context hook in a project.

This installer never removes or replaces existing MCP configuration.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path

GENERATED_MARKER = "// Generated by CogniGraph."


def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            file.write(text)
            file.flush()
            os.fsync(file.fileno())
        os.replace(temp_name, path)
    finally:
        if os.path.exists(temp_name):
            os.unlink(temp_name)


def install(project_root: str, python_path: str | None = None) -> dict:
    root = Path(project_root).expanduser().resolve()
    if not root.is_dir():
        raise ValueError("Project root does not exist")
    code_root = Path(__file__).resolve().parent
    source = code_root / "integrations" / "opencode-v2" / "index.ts.template"
    bridge = code_root / "opencode_context.py"
    if not source.is_file() or not bridge.is_file():
        raise FileNotFoundError("CogniGraph's plugin template or bridge is missing")

    plugin = root / ".opencode" / "plugins" / "cognigraph" / "index.ts"
    if plugin.exists() and not plugin.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
        raise FileExistsError(f"Refusing to overwrite a custom plugin: {plugin}")

    python = python_path or sys.executable
    rendered = source.read_text(encoding="utf-8")
    rendered = rendered.replace("__COGNIGRAPH_PYTHON_JSON__", json.dumps(python))
    rendered = rendered.replace("__COGNIGRAPH_BRIDGE_JSON__", json.dumps(str(bridge)))

    # OpenCode V2's documented plugin package dependency. Preserve other
    # .opencode/package.json fields and existing dependency choices.
    manifest = root / ".opencode" / "package.json"
    package = json.loads(manifest.read_text(encoding="utf-8")) if manifest.exists() else {}
    if not isinstance(package, dict) or not isinstance(package.get("dependencies", {}), dict):
        raise ValueError("Invalid .opencode/package.json")
    dependencies = dict(package.get("dependencies", {}))
    if "@opencode/plugin" not in dependencies:
        dependencies["@opencode/plugin"] = "latest"
    package["dependencies"] = dependencies

    _write_atomic(plugin, rendered)
    _write_atomic(manifest, json.dumps(package, indent=2, ensure_ascii=False) + "\n")
    return {"plugin": str(plugin), "manifest": str(manifest), "bridge": str(bridge)}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Install CogniGraph native OpenCode V2 context hook")
    parser.add_argument("--root", required=True, help="Target project root")
    parser.add_argument("--python", help="Python interpreter with CogniGraph dependencies (default: current Python)")
    args = parser.parse_args(argv)
    try:
        print(json.dumps(install(args.root, args.python), indent=2))
        return 0
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        print(f"Installation failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
